#!/bin/bash
# Prints the Homebrew formula for a release of the standalone build, for the
# tap at github.com/Softjey/homebrew-tap:
#
#   scripts/homebrew-formula.sh 0.2.0 checksums.txt > Formula/claude-profiler.rb
#
# A third argument names the formula, for a canary that must not replace the
# real one: `claude-profiler-canary` becomes `class ClaudeProfilerCanary`, which
# conflicts with `claude-profiler` since both install the same binary.
#
# `checksums.txt` is the release's: "<sha256>  claude-profiler-cli-<os>-<arch>.tar.gz"
# per line, as `shasum -a 256` writes it.
set -euo pipefail

version="${1:?usage: $0 <version> <checksums.txt>}"
checksums="${2:?usage: $0 <version> <checksums.txt>}"
name="${3:-claude-profiler}"
base="https://github.com/Softjey/claude-profiler/releases/download/v$version"

class_name="$(echo "$name" | awk -F- '{ for (i = 1; i <= NF; i++) printf "%s%s", toupper(substr($i, 1, 1)), substr($i, 2) }')"
conflicts=""
if [[ "$name" != claude-profiler ]]; then
  conflicts=$'\n  conflicts_with "claude-profiler"'
fi

sha() {
  local sum
  sum="$(awk -v f="claude-profiler-cli-$1.tar.gz" '$2 == f || $2 == "*" f { print $1 }' "$checksums")"
  if [[ -z "$sum" ]]; then
    echo "error: claude-profiler-cli-$1.tar.gz is not in $checksums" >&2
    exit 1
  fi
  echo "$sum"
}

# Looked up before the heredoc: a failure inside its $(...) would not stop the
# script, and a formula with an empty sha256 would go out.
macos_arm64="$(sha macos-arm64)"
macos_x64="$(sha macos-x64)"
linux_arm64="$(sha linux-arm64)"
linux_x64="$(sha linux-x64)"

cat <<EOF
# Generated by scripts/homebrew-formula.sh in Softjey/claude-profiler on each release.
class $class_name < Formula
  desc "See where the time went in a Claude Code session"
  homepage "https://github.com/Softjey/claude-profiler"
  version "$version"
  license "MIT"$conflicts

  on_macos do
    on_arm do
      url "$base/claude-profiler-cli-macos-arm64.tar.gz"
      sha256 "$macos_arm64"
    end
    on_intel do
      url "$base/claude-profiler-cli-macos-x64.tar.gz"
      sha256 "$macos_x64"
    end
  end

  on_linux do
    on_arm do
      url "$base/claude-profiler-cli-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/claude-profiler-cli-linux-x64.tar.gz"
      sha256 "$linux_x64"
    end
  end

  def install
    bin.install "claude-profiler"
    bin.install_symlink "claude-profiler" => "cprof"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/claude-profiler --version").strip
  end
end
EOF
